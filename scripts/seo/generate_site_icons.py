#!/usr/bin/env python3
"""Generate each wedding site's favicon, touch icon, manifest icons and og.png.

Purpose:
- One Worker serves four canonical hosts from one build, so a file in public/ is
  the same bytes on every host. Each site needs its own icon and share card, so
  the images are embedded in lib/site-icons.generated.ts and served per host by
  the route handlers under app/ (favicon.ico, apple-touch-icon.png, icon-192.png,
  icon-512.png, og.png, site.webmanifest), which read the request host.

Inputs:
- data/seo/site_homes.json: name, initial, background, accent, tagline per host.

Outputs:
- lib/site-icons.generated.ts (committed). Re-run after changing site_homes.json:
  python3 scripts/seo/generate_site_icons.py

Notes:
- Needs Pillow and a Georgia TTF (macOS ships one). CI never runs this; the
  generated module is the source of truth there, and the seo-hygiene favicon and
  og validators decode it and check sizes, so a stale or broken module fails.
"""
import base64, io, json, os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT_CANDIDATES = [
    '/System/Library/Fonts/Supplemental/Georgia Bold.ttf',
    '/System/Library/Fonts/Supplemental/Georgia.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf',
]
FONT_REGULAR = ['/System/Library/Fonts/Supplemental/Georgia.ttf', '/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf']
LINEN = '#FFFDF9'


def font(paths, size):
    for p in paths:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    sys.exit('generate_site_icons: no serif TTF found')


def square(site, size):
    img = Image.new('RGB', (size, size), site['background'])
    d = ImageDraw.Draw(img)
    pad = max(1, size // 16)
    d.rounded_rectangle([pad, pad, size - pad - 1, size - pad - 1], radius=size // 5, outline=site['accent'], width=max(1, size // 24))
    f = font(FONT_CANDIDATES, int(size * 0.62))
    d.text((size / 2, size / 2 + size * 0.02), site['initial'], font=f, fill=site['accent'], anchor='mm')
    return img


def og(site, host):
    w, h = 1200, 630
    img = Image.new('RGB', (w, h), site['background'])
    d = ImageDraw.Draw(img)
    d.rectangle([40, 40, w - 41, h - 41], outline=site['accent'], width=4)
    mark = square(site, 150)
    img.paste(mark, (90, 90))
    size = 76
    while size > 40 and d.textlength(site['name'], font=font(FONT_CANDIDATES, size)) > w - 180:
        size -= 2
    d.text((90, 300), site['name'], font=font(FONT_CANDIDATES, size), fill=LINEN)
    d.text((90, 405), site['tagline'], font=font(FONT_REGULAR, 36), fill=site['accent'])
    d.text((90, 520), host, font=font(FONT_REGULAR, 30), fill=LINEN)
    return img


def png(img, colors=None):
    buf = io.BytesIO()
    if colors:
        img = img.quantize(colors=colors)
    img.save(buf, format='PNG', optimize=True)
    return buf.getvalue()


def ico(site):
    buf = io.BytesIO()
    square(site, 48).save(buf, format='ICO', sizes=[(16, 16), (32, 32), (48, 48)])
    return buf.getvalue()


def main():
    data = json.load(open(os.path.join(ROOT, 'data/seo/site_homes.json')))
    out = {}
    for host, site in data['hosts'].items():
        out[host] = {
            'favicon.ico': ico(site),
            'apple-touch-icon.png': png(square(site, 180), 64),
            'icon-192.png': png(square(site, 192), 64),
            'icon-512.png': png(square(site, 512), 64),
            'og.png': png(og(site, host), 64),
        }
    lines = [
        '// GENERATED by scripts/seo/generate_site_icons.py from data/seo/site_homes.json. Do not edit.',
        '// Base64 image bytes per canonical host, served by the per-host route handlers in app/.',
        'export const SITE_ICON_FILES: Record<string, Record<string, string>> = {',
    ]
    for host, files in out.items():
        lines.append(f'  {json.dumps(host)}: {{')
        for name, raw in files.items():
            lines.append(f'    {json.dumps(name)}: {json.dumps(base64.b64encode(raw).decode())},')
        lines.append('  },')
    lines.append('};')
    path = os.path.join(ROOT, 'lib/site-icons.generated.ts')
    open(path, 'w').write('\n'.join(lines) + '\n')
    print(f'wrote {path} ({os.path.getsize(path)} bytes)')
    for host, files in out.items():
        print(host, {k: len(v) for k, v in files.items()})


if __name__ == '__main__':
    main()
